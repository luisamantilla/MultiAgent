import os
import pickle
import pandas as pd
import numpy as np
import json
from ...base_agent import BaseAgent  # Corrected import path
from openai import OpenAI

class AnalysisAgent(BaseAgent):
    def __init__(self, model="gpt-4.1", goal=None, role=None, detailed_prompt=None, memory_manager=None, iteration: int = 0, expertise: str = None):
        super().__init__(
            title="Analysis Agent",
            expertise=expertise or "Computational Biology, Data Analysis",
            goal=goal or "Analyze simulation results and provide insights or suggestions for further experiments.",
            role=role or "Simulation result analyst",
            model=model
        )
        self.detailed_prompt = detailed_prompt or (
            "You are a highly skilled scientific data analyst specializing in agent-based models of biological systems, particularly tumor and T cell interactions. "
            "You will be given experiment and data summaries. "
            "Your primary job is to:\\n"
            "1. Analyze the results in their biological context, paying close attention to units (e.g., time scales - clarify if ambiguous).\\n"
            "2. Highlight significant trends, anomalies, outliers, and particularly time-dependent dynamics if the data suggests temporal evolution (e.g., changes across timesteps or time points).\\n"
            "3. Suggest at least 2-3 possible next experiments. These suggestions should include not only new analyses but also specific modifications to the simulation's input parameters and rationale for these changes.\\n"
            "4. If you see any issues, unexpected results, or potential misinterpretations (e.g., confusing time scales), highlight them clearly.\\n"
            "Be thorough, use your scientific reasoning, and explain your findings clearly. "
            "If you need more data, specify what you need."
        )
        self.memory_manager = memory_manager
        self.iteration = iteration
        self.client = OpenAI()

    def summarize_pkl(self, file_path):
        with open(file_path, "rb") as f:
            data = pickle.load(f)
        summary = ""
        if isinstance(data, dict):
            summary += f"Top-level keys: {list(data.keys())[:10]}\n"
            # Try to summarize the first timestep if present
            first_key = list(data.keys())[0]
            first_val = data[first_key]
            if isinstance(first_val, dict):
                summary += f"First entry keys: {list(first_val.keys())}\n"
                # Try to summarize nested structure
                for k, v in first_val.items():
                    if isinstance(v, dict):
                        summary += f"  {k}: dict with keys {list(v.keys())[:5]}\n"
                    elif isinstance(v, (list, np.ndarray)):
                        summary += f"  {k}: list/array of length {len(v)}\n"
                    else:
                        summary += f"  {k}: {type(v).__name__}\n"
            else:
                summary += f"First entry type: {type(first_val).__name__}\n"
        else:
            summary += f"Data type: {type(data).__name__}\n"
        return summary

    def summarize_csv(self, file_path):
        df = pd.read_csv(file_path)
        summary = f"CSV shape: {df.shape}\nColumns: {list(df.columns)}\nHead:\n{df.head().to_string()}\n"
        summary += f"Describe:\n{df.describe().to_string()}\n"
        return summary

    def perform_task(self, experiment_summary, textual_data_summary, structured_file_summaries, custom_instruction=None, output_path=None):
        """
        Analyze results in the biological context, highlight trends/anomalies, suggest next experiments,
        and generate Python code snippets for deeper data analysis of CSV files.
        experiment_summary: summary from ExecutorAgent (can be short or long)
        textual_data_summary: textual summary from SummarizerAgent (long_summary)
        structured_file_summaries: list of dicts, with previews/stats for each file from SummarizerAgent
        Pass in the long summary for richer analysis, or the short summary for memory-efficient workflows.
        """
        prompt = (
            f"You are an expert in computational biology and data analysis, specializing in agent-based models.\\n"
            f"Given the following experiment summary, textual data summary, and structured file summaries, analyze the results broadly.\\n"
            f"The structured file summaries contain previews and statistics of data files (like CSVs or pickled objects) generated by the simulation.\\n"
            f"Focus on quantitative insights. Pay close attention to units (e.g., time scales like hours vs. seconds) and state any assumptions you make. If data appears to be time-series (e.g., pickle keys as timesteps, time columns in CSVs), analyze time-dependent dynamics, such as growth rates, decay rates, or oscillatory patterns.\\n"
            f"What are the key findings? What next experiments or analysis would you recommend? When recommending next experiments, suggest specific changes to the simulation's input parameters and explain the biological or scientific question these changes would address.\\n"
            f"Do not assume you have access to the full data—base your answer on the summaries provided.\\n"
            f"\\n"
            f"Additionally, if you identify specific questions or hypotheses that could be addressed by further computation on any CSV data provided in the 'structured_file_summaries', please:\\n"
            f"1. Clearly state the question/hypothesis. This could include investigating time-dependent behavior if applicable.\\n"
            f"2. Generate a Python code snippet using the pandas library that would perform this analysis on the relevant CSV file. Assume the CSV path will be provided to the script, or use a placeholder like 'path/to/your/data.csv'. The code should be robust and clear.\\n"
            f"3. Explain what the code does and what insights it might yield, especially concerning dynamics or parameter sensitivities.\\n"
            f"4. Enclose the Python code within triple backticks, like this: ```python\\n# your code here\\n```\\n"
            f"\\n---\\nExperiment summary (what was run, including any known parameters):\\n{experiment_summary}\\n---\\n"
            f"Textual data summary (overall interpretation of outputs):\\n{textual_data_summary}\\n---\\n"
            f"Structured file summaries (data previews and stats):\\n{json.dumps(structured_file_summaries, indent=2)}\\n---\\n"
            f"Your analysis and code suggestions (be mindful of time scales and suggest parameter changes for new experiments):"
        )
        if custom_instruction:
            prompt = custom_instruction + "\n" + prompt
        response = self.client.chat.completions.create(
            model=self.model,
            messages=[{"role": "user", "content": prompt}],
            max_tokens=10000
        )
        analysis_report = response.choices[0].message.content
        # Now generate a short summary for memory (≤512 tokens)
        summary_prompt = (
            f"Summarize the following analysis in ≤512 tokens (about 2000 characters). "
            f"Highlight the main findings and the most important next-step suggestions.\n\n---\n{analysis_report}\n---\nSummary (≤512 tokens):"
        )
        summary_response = self.client.chat.completions.create(
            model=self.model,
            messages=[{"role": "user", "content": summary_prompt}],
            max_tokens=512
        )
        short_summary = summary_response.choices[0].message.content[:2000]
        # Save to memory if manager is provided
        if self.memory_manager:
            self.memory_manager.write_memory(
                iteration=self.iteration,
                agent="AnalysisAgent",
                summary=short_summary,
                output_file=output_path or ""
            )
        # Optionally save analysis report
        if output_path:
            with open(output_path, "w") as f:
                f.write(analysis_report)
        return analysis_report, short_summary